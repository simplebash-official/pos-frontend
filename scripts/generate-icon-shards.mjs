/**
 * Regenerates `src/shared/lib/tablerIconShards/` from the installed `@tabler/icons-react`.
 *
 * The picker offers every icon in the library (~6000), which as one module is a 2.6 MB chunk on
 * whatever page touches it. Splitting the re-exports into one module per leading letter lets a
 * screen that only renders a few category icons download just the shards those names fall in,
 * while the picker pulls all of them on demand. Rolldown tree-shakes each `export { … } from
 * '@tabler/icons-react'` down to the named icons, so no deep dist paths are needed.
 *
 * Run with `npm run generate:icons` after bumping @tabler/icons-react, then `npm run format`.
 */
import { readFileSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDir, '..');
const barrelPath = resolve(
  projectRoot,
  'node_modules/@tabler/icons-react/dist/esm/tabler-icons-react.mjs'
);
const outDir = resolve(projectRoot, 'src/shared/lib/tablerIconShards');

/** Every `Icon*` name the package's barrel exports, including its alias exports. */
const readIconNames = () => {
  const source = readFileSync(barrelPath, 'utf8');
  const names = new Set();
  for (const statement of source.matchAll(/^export \{([^}]*)\} from '[^']*';$/gm)) {
    for (const clause of statement[1].split(',')) {
      const exported = clause
        .trim()
        .split(/\s+as\s+/)
        .pop();
      if (exported && exported.startsWith('Icon')) names.add(exported);
    }
  }
  return [...names].sort();
};

/** Shard key for an icon name: its first letter after the `Icon` prefix, or `_` for digits. */
const shardKeyForIcon = (name) => {
  const first = name.slice(4, 5).toLowerCase();
  return first >= 'a' && first <= 'z' ? first : '_';
};

const shards = new Map();
for (const name of readIconNames()) {
  const key = shardKeyForIcon(name);
  if (!shards.has(key)) shards.set(key, []);
  shards.get(key).push(name);
}

const keys = [...shards.keys()].sort();
const header = '// Generated by scripts/generate-icon-shards.mjs — do not edit by hand.\n';

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

for (const key of keys) {
  const names = shards.get(key);
  writeFileSync(
    resolve(outDir, `${key}.ts`),
    `${header}export { ${names.join(', ')} } from '@tabler/icons-react';\n`
  );
}

const loaderEntries = keys.map((key) => `  '${key}': () => import('./${key}'),`).join('\n');
writeFileSync(
  resolve(outDir, 'index.ts'),
  `${header}/** Shard key -> loader, keyed exactly as \`shardKeyForIcon\` in the generator computes it. */
export const ICON_SHARD_LOADERS: Record<string, () => Promise<Record<string, unknown>>> = {
${loaderEntries}
};

export const ICON_SHARD_KEYS = Object.keys(ICON_SHARD_LOADERS);

/** The shard holding \`name\` (PascalCase, no \`Icon\` prefix), or null if it can't be in any shard. */
export const shardKeyForIconName = (name: string): string | null => {
  const first = name.slice(0, 1).toLowerCase();
  const key = first >= 'a' && first <= 'z' ? first : '_';
  return key in ICON_SHARD_LOADERS ? key : null;
};
`
);

const total = keys.reduce((sum, key) => sum + shards.get(key).length, 0);
console.log(`Wrote ${keys.length} shards covering ${total} icon exports to ${outDir}`);
